def visualizar(numero):
    for fila in range(9):
        for digito_char in numero:
            digito = int(digito_char)
            for col in range(9):
                if numeros[digito][fila][col] == 1:
                    print("■", end="")

                else:
                    print(" ", end="")
            print("  ", end="")
        print()


